"""Write-only managed SSH secrets. Encryption key is separate from ciphertext.

Filesystem/OS authority is still the boundary against a compromised service.
Backup includes a SEPARATE protected key sidecar; protect both as credentials.
"""
from contextlib import closing, contextmanager
import os
from pathlib import Path
import re
import sqlite3
import uuid
from cryptography.fernet import Fernet, InvalidToken
from fastapi import HTTPException

MAGIC = b'AIOPS-SSH-FERNET-1\n'


def root_for(db_path):
    return Path(os.environ.get('AI_OPS_CONNECTOR_SECRET_DIR') or Path(db_path).parent / 'connector-secrets')


def key_path(root):
    return Path(os.environ.get('AI_OPS_CONNECTOR_MASTER_KEY_FILE') or Path(root).parent / 'connector-keys' / 'master.key')


def secure_write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(path.parent, 0o700)
    with path.open('xb') as output:
        os.chmod(path, 0o600)
        output.write(data)
        output.flush()
        os.fsync(output.fileno())


def read_key(root):
    path = key_path(root)
    if path.is_symlink():
        raise ValueError('Unsafe key reference')
    key = path.read_bytes()
    Fernet(key)  # Validate, never generate replacement on a read path.
    return key


def decrypt_file(path, data=None):
    path = Path(path)
    if path.is_symlink():
        raise ValueError('Unsafe secret reference')
    data = path.read_bytes() if data is None else data
    if not data.startswith(MAGIC):
        raise ValueError('Unsupported secret envelope')
    return Fernet(read_key(path.parent)).decrypt(data[len(MAGIC):])


class ConnectorSecrets:
    def __init__(self, db_path):
        self.root = root_for(db_path)

    def write(self, value):
        target_key = key_path(self.root)
        self.root.mkdir(parents=True, exist_ok=True, mode=0o700)
        os.chmod(self.root, 0o700)
        if not target_key.exists():
            if any(self.root.glob('*.enc')):
                raise ValueError('Existing ciphertext has no master key; restore key before writing')
            try:
                secure_write(target_key, Fernet.generate_key())
            except FileExistsError:
                pass
        encrypted = MAGIC + Fernet(read_key(self.root)).encrypt(value.encode('utf-8'))
        path = self.root / (uuid.uuid4().hex + '.enc')
        secure_write(path, encrypted)
        return str(path.resolve())

    @contextmanager
    def mutation(self, body):
        value = getattr(body, 'ssh_secret', None)
        if value is None:
            yield body
            return
        path = None
        try:
            try:
                path = self.write(value.get_secret_value())
            except (OSError, ValueError):
                raise HTTPException(503, 'SSH credential storage unavailable; configuration was not saved') from None
            yield body.model_copy(update={'ssh_secret': None, 'ssh_secret_ref': path})
        except BaseException:
            if path:
                Path(path).unlink(missing_ok=True)
            raise


def refs_in(db_path):
    refs = []
    with closing(sqlite3.connect('file:' + Path(db_path).as_posix() + '?mode=ro', uri=True)) as db:
        if not db.execute("SELECT 1 FROM sqlite_master WHERE name='asset_connections'").fetchone():
            return refs
        for (ref,) in db.execute('SELECT ssh_secret_ref FROM asset_connections WHERE ssh_secret_ref IS NOT NULL'):
            p = Path(ref)
            # Managed filenames are generated by us; legacy secret paths are not
            # silently included in a database-only backup.
            if re.fullmatch(r'[0-9a-f]{32}\.enc', p.name):
                refs.append(ref)
    return sorted(set(refs))


def backup_managed(db_path, backup_path):
    refs = refs_in(db_path)
    root = Path(str(backup_path) + '.connector-secrets')
    keys = Path(str(backup_path) + '.connector-keys')
    for ref in refs:
        p = Path(ref)
        data = p.read_bytes()
        decrypt_file(p, data)  # Corruption/missing key must fail before success.
        key = read_key(p.parent)
        for target, value in ((root / p.name, data), (keys / (p.stem + '.key'), key)):
            if target.exists():
                if target.is_symlink() or target.read_bytes() != value:
                    raise ValueError('Managed credential backup revision conflict')
            else:
                secure_write(target, value)
    return len(refs)


def verify_managed(backup_path):
    for ref in refs_in(backup_path):
        name = Path(ref).name
        p = Path(str(backup_path) + '.connector-secrets') / name
        k = Path(str(backup_path) + '.connector-keys') / (Path(name).stem + '.key')
        if p.is_symlink() or k.is_symlink():
            raise ValueError('Unsafe backup reference')
        data = p.read_bytes()
        if not data.startswith(MAGIC):
            raise ValueError('Invalid managed credential backup')
        Fernet(k.read_bytes()).decrypt(data[len(MAGIC):])


def restore_managed(backup_path, staged_db, live_path):
    """Re-encrypt under destination key and rewrite ONLY the staged DB references."""
    store = ConnectorSecrets(live_path)
    created = []
    try:
        with closing(sqlite3.connect(staged_db)) as db:
            for ref in refs_in(backup_path):
                name = Path(ref).name
                ciphertext = (Path(str(backup_path) + '.connector-secrets') / name).read_bytes()
                key = (Path(str(backup_path) + '.connector-keys') / (Path(name).stem + '.key')).read_bytes()
                secret = Fernet(key).decrypt(ciphertext[len(MAGIC):]).decode('utf-8')
                new_ref = store.write(secret)
                created.append(new_ref)
                db.execute('UPDATE asset_connections SET ssh_secret_ref=? WHERE ssh_secret_ref=?', (new_ref, ref))
            db.commit()
    except BaseException:
        for path in created:
            Path(path).unlink(missing_ok=True)
        raise
    # The caller owns cleanup if later database installation fails.
    return created
